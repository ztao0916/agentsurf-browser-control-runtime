import { randomBytes } from 'node:crypto';
import { execFile } from 'node:child_process';
import { access, chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { getMessages } from './i18n.mjs';

const run = promisify(execFile);
const { nativeHost: text } = await getMessages();
const browsers = {
  chrome: { label: 'Chrome', defaultPort: 8765 },
  edge: { label: 'Edge', defaultPort: 8766 },
};

if (process.platform !== 'darwin') throw new Error(text.macOnly);
const options = parseArgs(process.argv.slice(2), text);
const { extensionId, legacy } = options;
const browser = legacy ? 'chrome' : options.browser;
const { label: browserLabel } = browsers[browser];
const port = options.port ?? browsers[browser].defaultPort;
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error(text.invalidPort);

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const hostScript = join(projectRoot, 'dist', 'native-host', 'host.js');
const mcpScript = join(projectRoot, 'dist', 'mcp', 'cli.js');
await access(hostScript);
await access(mcpScript);
const supportDirectory = join(homedir(), 'Library', 'Application Support');
const runtimeRoot = join(supportDirectory, 'BrowserControlRuntime');
const runtimeDirectory = legacy ? runtimeRoot : join(runtimeRoot, browser);
const configPath = join(runtimeDirectory, 'config.json');
const legacyConfigPath = join(runtimeRoot, 'config.json');
const launcherPath = join(runtimeDirectory, 'native-host.sh');
const mcpLauncherPath = join(runtimeDirectory, 'agentsurf-mcp.sh');
const manifestDirectory = browser === 'edge'
  ? join(supportDirectory, 'Microsoft Edge', 'NativeMessagingHosts')
  : join(supportDirectory, 'Google', 'Chrome', 'NativeMessagingHosts');
const manifestPath = join(manifestDirectory, 'com.browsercontrol.runtime.json');

let token;
try {
  const config = JSON.parse(await readFile(
    !legacy && browser === 'chrome' && !(await fileExists(configPath)) ? legacyConfigPath : configPath,
    'utf8',
  ));
  if (typeof config.token !== 'string' || config.token.length < 16) {
    throw new Error(text.invalidToken(configPath));
  }
  token = config.token;
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  token = randomBytes(32).toString('hex');
}

await mkdir(runtimeDirectory, { recursive: true, mode: 0o700 });
await mkdir(manifestDirectory, { recursive: true });
await writeFile(configPath, `${JSON.stringify({ port, token }, null, 2)}\n`, { mode: 0o600 });
await chmod(configPath, 0o600);

// Quote absolute paths: GUI-launched Chrome does not inherit the terminal's Node PATH.
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;
await writeFile(launcherPath, `#!/bin/sh\nexport BROWSER_BRIDGE_CONFIG=${quote(configPath)}\nexec ${quote(process.execPath)} ${quote(hostScript)}\n`, { mode: 0o700 });
await chmod(launcherPath, 0o700);

// An MCP client spawns its server with an unpredictable working directory (and GUI clients often see
// a narrow PATH), so give it one stable absolute entry point. Regenerated by every install, which is
// also what a moved project or a switched Node version needs anyway.
await writeFile(
  mcpLauncherPath,
  `#!/bin/sh\nexport BROWSER_BRIDGE_CONFIG=${quote(configPath)}\nexec ${quote(process.execPath)} ${quote(mcpScript)} "$@"\n`,
  { mode: 0o700 },
);
await chmod(mcpLauncherPath, 0o700);

// Fail the install instead of shipping a launcher that cannot start the server. The CLI prints its
// usage on stderr and exits 0, so a resolved promise is the success signal. This cannot replace a
// real end-to-end check on macOS hardware, but it does catch a wrong interpreter or script path.
try {
  await run(mcpLauncherPath, ['help']);
} catch (error) {
  throw new Error(text.launcherCheckFailed(mcpLauncherPath, error instanceof Error ? error.message : String(error)));
}

await writeFile(manifestPath, `${JSON.stringify({
  name: 'com.browsercontrol.runtime',
  description: `AgentSurf native messaging host for ${browserLabel}`,
  path: launcherPath,
  type: 'stdio',
  allowed_origins: [`chrome-extension://${extensionId}/`],
}, null, 2)}\n`);

console.log(text.installed(browserLabel, extensionId));
console.log(text.manifest(manifestPath));
console.log(text.config(configPath));
console.log(text.bridge(port));
console.log(text.reload(browserLabel));
console.log('');
console.log(text.mcpConfig(browserLabel));
console.log('');
const mcpName = legacy ? 'agentsurf' : `agentsurf-${browser}`;
console.log(JSON.stringify({ mcpServers: { [mcpName]: { command: mcpLauncherPath } } }, null, 2));

function parseArgs(values, text) {
  let browser = 'chrome';
  let browserProvided = false;
  let legacy = false;
  let extensionId;
  let port;
  let help = false;
  const positional = [];

  for (let index = 0; index < values.length; index += 1) {
    const arg = values[index];
    if (arg === '--help' || arg === '-h') {
      help = true;
      continue;
    }
    if (arg === '--legacy') {
      legacy = true;
      continue;
    }
    if (arg === '--browser' || arg === '--extension-id' || arg === '--port') {
      const value = values[index + 1];
      if (value === undefined || value.startsWith('--')) throw new Error(text.missingOptionValue(arg));
      index += 1;
      if (arg === '--browser') {
        browser = value;
        browserProvided = true;
      }
      else if (arg === '--extension-id') extensionId = value;
      else port = Number(value);
      continue;
    }
    if (arg.startsWith('--')) throw new Error(text.unknownOption(arg));
    positional.push(arg);
  }

  if (help) {
    console.log(text.usage);
    process.exit(0);
  }
  if (positional.length > 0 && extensionId === undefined) extensionId = positional.shift();
  if (positional.length > 0 && port === undefined) {
    port = Number(positional.shift());
  }
  if (positional.length > 0) throw new Error(text.usage);
  if (legacy && browserProvided) throw new Error('--legacy cannot be combined with --browser.');
  legacy ||= !browserProvided;
  if (browser !== 'chrome' && browser !== 'edge') throw new Error(text.invalidBrowser(browser));
  if (!/^[a-p]{32}$/.test(extensionId ?? '')) throw new Error(text.invalidExtensionId);
  return { browser, extensionId, legacy, port };
}

async function fileExists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}
