import { randomBytes } from 'node:crypto';
import { execFile } from 'node:child_process';
import { access, chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { getMessages } from './i18n.mjs';

const run = promisify(execFile);
const { nativeHost: text } = await getMessages();

if (process.platform !== 'darwin') throw new Error(text.macOnly);
const [extensionId, portValue = '8765', ...extra] = process.argv.slice(2);
if (!/^[a-p]{32}$/.test(extensionId ?? '') || extra.length > 0) {
  throw new Error(text.usage);
}
const port = Number(portValue);
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error(text.invalidPort);

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const hostScript = join(projectRoot, 'dist', 'native-host', 'host.js');
const mcpScript = join(projectRoot, 'dist', 'mcp', 'cli.js');
await access(hostScript);
await access(mcpScript);
const runtimeDirectory = join(homedir(), 'Library', 'Application Support', 'BrowserControlRuntime');
const configPath = join(runtimeDirectory, 'config.json');
const launcherPath = join(runtimeDirectory, 'native-host.sh');
const mcpLauncherPath = join(runtimeDirectory, 'agentsurf-mcp.sh');
const manifestDirectory = join(homedir(), 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts');
const manifestPath = join(manifestDirectory, 'com.browsercontrol.runtime.json');

let token;
try {
  const config = JSON.parse(await readFile(configPath, 'utf8'));
  if (typeof config.token !== 'string' || config.token.length < 16) {
    throw new Error(text.invalidToken(configPath));
  }
  token = config.token;
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  token = randomBytes(32).toString('hex');
}

await mkdir(runtimeDirectory, { recursive: true, mode: 0o700 });
await mkdir(manifestDirectory, { recursive: true });
await writeFile(configPath, `${JSON.stringify({ port, token }, null, 2)}\n`, { mode: 0o600 });
await chmod(configPath, 0o600);

// Quote absolute paths: GUI-launched Chrome does not inherit the terminal's Node PATH.
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;
await writeFile(launcherPath, `#!/bin/sh\nexport BROWSER_BRIDGE_CONFIG=${quote(configPath)}\nexec ${quote(process.execPath)} ${quote(hostScript)}\n`, { mode: 0o700 });
await chmod(launcherPath, 0o700);

// An MCP client spawns its server with an unpredictable working directory (and GUI clients often see
// a narrow PATH), so give it one stable absolute entry point. Regenerated by every install, which is
// also what a moved project or a switched Node version needs anyway.
await writeFile(mcpLauncherPath, `#!/bin/sh\nexec ${quote(process.execPath)} ${quote(mcpScript)} "$@"\n`, { mode: 0o700 });
await chmod(mcpLauncherPath, 0o700);

// Fail the install instead of shipping a launcher that cannot start the server. The CLI prints its
// usage on stderr and exits 0, so a resolved promise is the success signal. This cannot replace a
// real end-to-end check on macOS hardware, but it does catch a wrong interpreter or script path.
try {
  await run(mcpLauncherPath, ['help']);
} catch (error) {
  throw new Error(text.launcherCheckFailed(mcpLauncherPath, error instanceof Error ? error.message : String(error)));
}

await writeFile(manifestPath, `${JSON.stringify({
  name: 'com.browsercontrol.runtime',
  description: 'AgentSurf native messaging host',
  path: launcherPath,
  type: 'stdio',
  allowed_origins: [`chrome-extension://${extensionId}/`],
}, null, 2)}\n`);

console.log(text.installed(extensionId));
console.log(text.manifest(manifestPath));
console.log(text.config(configPath));
console.log(text.bridge(port));
console.log(text.reload);
console.log('');
console.log(text.mcpConfig);
console.log('');
console.log(JSON.stringify({ mcpServers: { agentsurf: { command: mcpLauncherPath } } }, null, 2));
